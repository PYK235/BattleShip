IF DB_ID(N'BattleShipPart3') IS NULL CREATE DATABASE BattleShipPart3;
GO
USE BattleShipPart3;
GO
IF OBJECT_ID('dbo.Matches','U') IS NULL CREATE TABLE dbo.Matches(
	MatchId BIGINT IDENTITY PRIMARY KEY, Player1 NVARCHAR(50) NOT NULL, Player2 NVARCHAR(50) NOT NULL,
	Status VARCHAR(16) NOT NULL DEFAULT 'SETUP', Winner NVARCHAR(50) NULL, ActivePlayer NVARCHAR(50) NULL,
	CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), StartedAt DATETIME2 NULL, FinishedAt DATETIME2 NULL);
IF OBJECT_ID('dbo.PlayerBoards','U') IS NULL CREATE TABLE dbo.PlayerBoards(
	MatchId BIGINT NOT NULL REFERENCES dbo.Matches(MatchId), PlayerName NVARCHAR(50) NOT NULL,
	BoardState CHAR(36) NOT NULL DEFAULT REPLICATE('0',36), Ready BIT NOT NULL DEFAULT 0,
	ShotsTaken INT NOT NULL DEFAULT 0, CONSTRAINT PK_PlayerBoards PRIMARY KEY(MatchId,PlayerName));
IF OBJECT_ID('dbo.GameEvents','U') IS NULL CREATE TABLE dbo.GameEvents(
	EventId BIGINT IDENTITY PRIMARY KEY, MatchId BIGINT NOT NULL REFERENCES dbo.Matches(MatchId),
	PlayerName NVARCHAR(50) NOT NULL, EventType VARCHAR(20) NOT NULL, Details NVARCHAR(300) NULL,
	CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME());
GO

USE BattleShipPart3;

SELECT TABLE_SCHEMA, TABLE_NAME
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_NAME;